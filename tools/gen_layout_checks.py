"""Generate C++ static_asserts that pin the shared C++/Slang structs to the shader layout.

Usage: python tools/gen_layout_checks.py [--spirv DIR] [--out FILE] [--check]

Reads member names and offsets of the shared structs from the built SPIR-V
(run tools/build_shaders.py first) and writes include/numos/detail/layout_checks.h.
With --check, exits non-zero if the committed file is out of date instead of writing it.
"""
import argparse
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Shared struct -> SPIR-V file that contains its scalar-layout ("_natural") version.
STRUCTS = {
    'AtmosphereArgs': 'cloud_render.comp.spv',
    'MoonParams': 'cloud_render.comp.spv',
    'Camera': 'cloud_render.comp.spv',
    'AerialPerspectiveLight': 'aerial_perspective_light_cull.comp.spv',
    'CloudNvdfJfaArgs': 'cloud_nvdf_jfa.comp.spv',
    'GroundProbeArgs': 'ground_probe.comp.spv',
    'GenerateMipmapArgs': 'generate_mipmap.comp.spv',
}


class Module:
    def __init__(self, path):
        data = path.read_bytes()
        w = struct.unpack('<%dI' % (len(data) // 4), data)
        self.names, self.members, self.offsets, self.strides, self.types, self.consts = {}, {}, {}, {}, {}, {}
        i = 5
        while i < len(w):
            op, n = w[i] & 0xffff, w[i] >> 16
            args = w[i + 1:i + n]
            if op == 5:    # OpName
                self.names[args[0]] = self._str(args[1:])
            elif op == 6:  # OpMemberName
                self.members.setdefault(args[0], {})[args[1]] = self._str(args[2:])
            elif op == 72 and args[2] == 35:  # OpMemberDecorate Offset
                self.offsets.setdefault(args[0], {})[args[1]] = args[3]
            elif op == 71 and args[1] == 6:   # OpDecorate ArrayStride
                self.strides[args[0]] = args[2]
            elif op in (21, 22, 23, 24, 28, 30):  # Int Float Vector Matrix Array Struct
                self.types[args[0]] = (op, args[1:])
            elif op == 43:  # OpConstant
                self.consts[args[1]] = args[2]
            i += n

    @staticmethod
    def _str(words):
        return struct.pack('<%dI' % len(words), *words).split(b'\0')[0].decode()

    def size(self, t):
        op, a = self.types[t]
        if op in (21, 22):
            return a[0] // 8
        if op == 23:
            return self.size(a[0]) * a[1]
        if op == 24:
            return self.size(a[0]) * a[1]
        if op == 28:
            return self.strides[t] * self.consts[a[1]]
        if op == 30:
            last = max(self.offsets[t])
            return self.offsets[t][last] + self.size(a[last])
        raise ValueError(op)

    def find(self, name):
        for tid, n in self.names.items():
            if n == name + '_natural' and tid in self.types:
                return tid
        raise KeyError(name)


def generate(spirv_dir):
    out = ['// Copyright 2026 Kim2091 (Sparkles)',
           '// SPDX-License-Identifier: Apache-2.0',
           '// GENERATED by tools/gen_layout_checks.py from the built SPIR-V. Do not edit.',
           '// Fails the C++ build if a shared struct drifts from the shader layout.',
           '#pragma once',
           '',
           '#include <cstddef>',
           '#include "numos/lib/atmosphere_args.h"',
           '#include "numos/lib/aerial_perspective_light.h"',
           '#include "numos/lib/cloud_nvdf.h"',
           '#include "numos/util/camera.h"',
           '#include "numos/lib/generate_mipmap.h"',
           '#include "numos/lib/ground_probe.h"',
           '',
           'namespace numos::detail {',
           '']
    for name, spv in STRUCTS.items():
        m = Module(spirv_dir / spv)
        t = m.find(name)
        out.append(f'// {name}: {len(m.offsets[t])} members, {m.size(t)} bytes in the shader layout')
        for idx in sorted(m.offsets[t]):
            member = m.members[t][idx]
            out.append(f'static_assert(offsetof({name}, {member}) == {m.offsets[t][idx]}, "{name}::{member} offset differs from the shader");')
        out.append(f'static_assert(sizeof({name}) >= {m.size(t)}, "{name} is smaller than the shader layout");')
        out.append('')
    out.append('} // namespace numos::detail')
    out.append('')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--spirv', default=str(ROOT / 'build' / 'spirv'))
    ap.add_argument('--out', default=str(ROOT / 'include' / 'numos' / 'detail' / 'layout_checks.h'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = generate(pathlib.Path(a.spirv))
    out = pathlib.Path(a.out)
    if a.check:
        current = out.read_text(encoding='utf-8') if out.exists() else ''
        if current.replace('\r\n', '\n') != text:
            sys.exit(f'{out} is out of date; run tools/gen_layout_checks.py')
        print('layout checks up to date')
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(f'wrote {out} ({text.count("static_assert")} checks)')


if __name__ == '__main__':
    main()
