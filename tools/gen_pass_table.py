"""Generate the pass table (src/generated/passes.inc) from the built SPIR-V.

Usage: python tools/gen_pass_table.py [--spirv DIR] [--check]

For every variant: name, SPIR-V file, FNV-1a hash of the file, workgroup size, push-constant
size, and every descriptor binding with its kind. The host builds its pipelines from this table
and the SPIR-V files (numos::passes(), numos::loadPassSpirv()).
"""
import argparse
import pathlib
import struct
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_layout_checks import Module  # noqa: E402  (exact SPIR-V type sizes)

ROOT = pathlib.Path(__file__).resolve().parent.parent

# SPIR-V enums used below.
OP_NAME, OP_DECORATE, OP_TYPE_IMAGE, OP_TYPE_SAMPLER, OP_TYPE_SAMPLED_IMAGE = 5, 71, 25, 26, 27
OP_TYPE_ARRAY, OP_TYPE_RUNTIME_ARRAY, OP_TYPE_STRUCT, OP_TYPE_POINTER, OP_VARIABLE = 28, 29, 30, 32, 59
OP_EXECUTION_MODE, OP_MEMBER_DECORATE, OP_TYPE_ACCEL = 16, 72, 5341
DEC_BINDING, DEC_SET, DEC_BLOCK, DEC_BUFFER_BLOCK, DEC_OFFSET, DEC_NON_WRITABLE = 33, 34, 2, 3, 35, 24
SC_UNIFORM_CONSTANT, SC_UNIFORM, SC_PUSH_CONSTANT, SC_STORAGE_BUFFER = 0, 2, 9, 12
EXEC_LOCAL_SIZE = 17


def fnv1a(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def reflect(path):
    data = path.read_bytes()
    w = struct.unpack('<%dI' % (len(data) // 4), data)
    names, binding, dset, types, ptrs, varz, block, bufblock, nonwritable, offsets = {}, {}, {}, {}, {}, {}, set(), set(), set(), {}
    local = (1, 1, 1)
    i = 5
    while i < len(w):
        op, n = w[i] & 0xffff, w[i] >> 16
        a = w[i + 1:i + n]
        if op == OP_NAME:
            names[a[0]] = struct.pack('<%dI' % (n - 2), *a[1:]).split(b'\0')[0].decode()
        elif op == OP_DECORATE:
            if a[1] == DEC_BINDING: binding[a[0]] = a[2]
            elif a[1] == DEC_SET: dset[a[0]] = a[2]
            elif a[1] == DEC_BLOCK: block.add(a[0])
            elif a[1] == DEC_BUFFER_BLOCK: bufblock.add(a[0])
            elif a[1] == DEC_NON_WRITABLE: nonwritable.add(a[0])
        elif op == OP_MEMBER_DECORATE and a[2] == DEC_OFFSET:
            offsets.setdefault(a[0], []).append(a[3])
        elif op == OP_MEMBER_DECORATE and a[2] == DEC_NON_WRITABLE:
            nonwritable.add(a[0])
        elif op in (OP_TYPE_IMAGE, OP_TYPE_SAMPLER, OP_TYPE_SAMPLED_IMAGE, OP_TYPE_ARRAY, OP_TYPE_RUNTIME_ARRAY,
                    OP_TYPE_STRUCT, OP_TYPE_ACCEL):
            types[a[0]] = (op, a[1:])
        elif op == OP_TYPE_POINTER:
            ptrs[a[0]] = (a[1], a[2])
        elif op == OP_VARIABLE:
            varz[a[1]] = (a[0], a[2])
        elif op == OP_EXECUTION_MODE and a[1] == EXEC_LOCAL_SIZE:
            local = (a[2], a[3], a[4])
        i += n

    bindings, push = [], 0
    for var, (ptype, sc) in varz.items():
        _, pointee = ptrs[ptype]
        if sc == SC_PUSH_CONSTANT:
            push = Module(path).size(pointee)
            continue
        if var not in binding:
            continue
        t = pointee
        while types.get(t, (None,))[0] in (OP_TYPE_ARRAY, OP_TYPE_RUNTIME_ARRAY):
            t = types[t][1][0]
        op, args = types.get(t, (None, ()))
        dim, fmt = 'None', 0
        img = None
        if op == OP_TYPE_IMAGE:
            img = args
        elif op == OP_TYPE_SAMPLED_IMAGE:
            img = types[args[0]][1]
        if img is not None:
            # OpTypeImage: sampled type, Dim (1 = 2D, 2 = 3D), Depth, Arrayed, MS, Sampled, Format
            dim = {1: 'Tex2D', 2: 'Tex3D'}.get(img[1], 'Tex2D')
            if img[3]:
                dim = 'Tex2DArray'
            fmt = img[6]
        if op == OP_TYPE_IMAGE:
            sampled = args[5]  # 1 = sampled, 2 = storage
            kind = 'SampledTexture' if sampled == 1 else 'StorageTexture'
        elif op == OP_TYPE_SAMPLER:
            kind = 'Sampler'
        elif op == OP_TYPE_SAMPLED_IMAGE:
            kind = 'CombinedTextureSampler'
        elif op == OP_TYPE_ACCEL:
            kind = 'AccelerationStructure'
        elif op == OP_TYPE_STRUCT:
            if sc == SC_UNIFORM and t in block:
                kind = 'ConstantBuffer'
            else:
                kind = 'StructuredBuffer' if (var in nonwritable or t in nonwritable) else 'RWStructuredBuffer'
        else:
            kind = 'SampledTexture'
        bindings.append((binding[var], dset.get(var, 0), kind, dim, fmt, names.get(var, '')))
    return local, push, sorted(bindings)


def generate(spirv_dir):
    lines = ['// Copyright 2026 Kim2091 (Sparkles)',
             '// SPDX-License-Identifier: Apache-2.0',
             '// GENERATED by tools/gen_pass_table.py from the built SPIR-V. Do not edit.',
             '// NUMOS_PASS(name, file, hash, localX, localY, localZ, pushConstantBytes, bindingsBegin, bindingsCount)',
             '// NUMOS_PASS_BINDING(slot, set, kind, dim, spirvImageFormat, "shader variable")',
             '']
    passes, binds = [], []
    for spv in sorted(spirv_dir.glob('*.spv')):
        local, push, b = reflect(spv)
        name = spv.name[:-len('.comp.spv')]
        passes.append(f'NUMOS_PASS({name}, "{spv.name}", 0x{fnv1a(spv.read_bytes()):016x}ull, '
                      f'{local[0]}, {local[1]}, {local[2]}, {push}, {len(binds)}, {len(b)})')
        for slot, s, kind, dim, fmt, var in b:
            binds.append(f'NUMOS_PASS_BINDING({slot}, {s}, {kind}, {dim}, {fmt}, "{var}")')
    lines += ['#ifdef NUMOS_PASS'] + passes + ['#undef NUMOS_PASS', '#endif', '',
              '#ifdef NUMOS_PASS_BINDING'] + binds + ['#undef NUMOS_PASS_BINDING', '#endif', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--spirv', default=str(ROOT / 'build' / 'spirv'))
    ap.add_argument('--out', default=str(ROOT / 'src' / 'generated' / 'passes.inc'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = generate(pathlib.Path(a.spirv))
    out = pathlib.Path(a.out)
    if a.check:
        cur = out.read_text(encoding='utf-8').replace('\r\n', '\n') if out.exists() else ''
        sys.exit(0 if cur == text else f'{out} is out of date; run tools/gen_pass_table.py')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(f'wrote {out}: {text.count("NUMOS_PASS(") - 1} passes, {text.count("NUMOS_PASS_BINDING(") - 1} bindings')


if __name__ == '__main__':
    main()
